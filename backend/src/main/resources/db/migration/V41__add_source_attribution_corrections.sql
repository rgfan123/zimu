CREATE FUNCTION app.validate_source_attribution_correction() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    recorded_channel VARCHAR(32);
    previous_channel VARCHAR(32);
    expected_no INTEGER;
BEGIN
    SELECT source_channel INTO STRICT recorded_channel
    FROM app.import_batches
    WHERE id=NEW.import_batch_id AND batch_type='SOURCE_ORDER'
    FOR UPDATE;

    SELECT attributed_source_channel INTO previous_channel
    FROM app.source_attribution_corrections
    WHERE import_batch_id=NEW.import_batch_id
    ORDER BY correction_no DESC LIMIT 1;

    SELECT COALESCE(MAX(correction_no), 0)+1 INTO expected_no
    FROM app.source_attribution_corrections WHERE import_batch_id=NEW.import_batch_id;

    IF NEW.correction_no <> expected_no THEN
        RAISE EXCEPTION 'source attribution correction_no must be sequential';
    END IF;
    IF NEW.attributed_source_channel = COALESCE(previous_channel, recorded_channel) THEN
        RAISE EXCEPTION 'source attribution correction must change the effective channel';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION app.validate_source_return_invalidation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    export_batch_id BIGINT;
    correction_batch_id BIGINT;
    export_push_status VARCHAR(16);
BEGIN
    SELECT import_batch_id, push_status INTO STRICT export_batch_id, export_push_status
    FROM app.source_return_exports WHERE id=NEW.source_return_export_id;
    SELECT import_batch_id INTO STRICT correction_batch_id
    FROM app.source_attribution_corrections WHERE id=NEW.source_attribution_correction_id;

    IF export_batch_id <> correction_batch_id THEN
        RAISE EXCEPTION 'source return invalidation must use a correction from the same import batch';
    END IF;
    IF export_push_status IN ('PUSHING', 'SUCCESS') THEN
        RAISE EXCEPTION 'a pushing or pushed source return export cannot be invalidated';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION app.validate_single_valid_final_source_return() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    -- 替代旧唯一索引后仍需由数据库串行化同批次 final 判定，避免并发双 final。
    PERFORM 1 FROM app.import_batches WHERE id=NEW.import_batch_id FOR UPDATE;
    IF NEW.is_final AND EXISTS (
        SELECT 1 FROM app.source_return_exports existing
        WHERE existing.import_batch_id=NEW.import_batch_id AND existing.is_final
          AND NOT EXISTS (
              SELECT 1 FROM app.source_return_export_invalidations invalidation
              WHERE invalidation.source_return_export_id=existing.id)
    ) THEN
        RAISE EXCEPTION 'source order batch already has a valid final return export';
    END IF;
    RETURN NEW;
END;
$$;

