    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_batch_id                 BIGINT NOT NULL REFERENCES app.import_batches(id) ON DELETE RESTRICT,
    correction_no                   INTEGER NOT NULL CHECK (correction_no > 0),
    attributed_source_channel       VARCHAR(32) NOT NULL
                                      CONSTRAINT source_attribution_corrections_channel_check
                                      CHECK (attributed_source_channel IN ('DAZHE', 'WANGQI')),
    attributed_template_family      VARCHAR(128) NOT NULL,
    attributed_template_fingerprint VARCHAR(128) NOT NULL,
    reason                          VARCHAR(500) NOT NULL,
