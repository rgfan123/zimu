        processing_status IS NULL
        OR (processing_status = 'RECEIVED'
            AND processing_claim_token IS NULL AND processing_attempt = 0)
        OR (processing_status <> 'RECEIVED'
            AND processing_claim_token IS NOT NULL AND processing_attempt >= 1)
    );

CREATE OR REPLACE FUNCTION app.guard_wecom_card_event_first_facts()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.event_type = 'template_card_event' AND (
        NEW.event_type IS DISTINCT FROM OLD.event_type
        OR NEW.msgid IS DISTINCT FROM OLD.msgid
        OR NEW.aibot_id IS DISTINCT FROM OLD.aibot_id
        OR NEW.chat_id IS DISTINCT FROM OLD.chat_id
        OR NEW.chat_type IS DISTINCT FROM OLD.chat_type
        OR NEW.from_user_id IS DISTINCT FROM OLD.from_user_id
        OR NEW.create_time IS DISTINCT FROM OLD.create_time
        OR NEW.raw_payload IS DISTINCT FROM OLD.raw_payload
        OR NEW.event_key IS DISTINCT FROM OLD.event_key
        OR NEW.task_id IS DISTINCT FROM OLD.task_id
        OR NEW.order_draft_id IS DISTINCT FROM OLD.order_draft_id
    ) THEN
        RAISE EXCEPTION 'template-card first facts are immutable'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_wecom_card_event_first_facts
    BEFORE UPDATE ON app.wecom_events
    FOR EACH ROW
    EXECUTE FUNCTION app.guard_wecom_card_event_first_facts();

