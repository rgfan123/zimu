-- Issues #87/#88: persisted order-draft cards, traceable click outcomes and 5s update state.

ALTER TABLE app.order_drafts
    ADD COLUMN settlement_time TIMESTAMPTZ;

-- Confirmed legacy drafts did not persist this fact on the draft, but their canonical order does.
UPDATE app.order_drafts d
SET settlement_time = o.settlement_time
FROM app.review_cases rc
JOIN app.orders o ON o.id = CASE
    WHEN rc.resolution->>'order_id' ~ '^[1-9][0-9]*$'
    THEN (rc.resolution->>'order_id')::BIGINT
END
WHERE rc.order_draft_id = d.id
  AND rc.status = 'RESOLVED'
  AND rc.resolution->>'resolution_type' = 'ORDER_DRAFT_CONFIRMED'
  AND d.status = 'CONFIRMED'
  AND d.settlement_time IS NULL;

-- Only open legacy drafts need a new missing-field gate. Closed historical drafts must not be
-- rewritten to look incomplete.
UPDATE app.order_drafts
SET missing_fields = missing_fields || '["settlement_time"]'::jsonb
WHERE status = 'OPEN'
  AND settlement_time IS NULL
  AND NOT (missing_fields ? 'settlement_time');

