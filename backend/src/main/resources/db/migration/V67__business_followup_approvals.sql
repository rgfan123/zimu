-- Never rewrite a correlation ID that may already exist on an externally delivered card. Legacy
-- rows remain exact-match capabilities in the outbox; all newly created rows use the opaque shape.

UPDATE app.wecom_order_draft_cards
SET task_id = 'order-draft_' || order_draft_id || '_v' || draft_revision
        || '_' || replace(gen_random_uuid()::text, '-', '')
WHERE status IN ('PENDING', 'FAILED')
  AND task_id ~ '^order-draft:[1-9][0-9]*$';

ALTER TABLE app.wecom_order_draft_cards
    DROP CONSTRAINT wecom_order_draft_cards_task_id_check,
    ADD CONSTRAINT wecom_order_draft_cards_task_id_check CHECK (
        task_id ~ '^order-draft:[1-9][0-9]*$'
        OR task_id ~ '^order-draft_[1-9][0-9]{0,18}_v[0-9]{1,19}_[0-9a-f]{32}$'
    );

UPDATE app.wecom_business_cards
SET task_id = regexp_replace(
        task_id,
        '^([a-z][a-z-]{0,31}):([0-9]{1,19}):([vg][0-9]{1,19})$',
        '\1_\2_\3') || '_' || replace(gen_random_uuid()::text, '-', '')
WHERE status IN ('PENDING', 'FAILED')
  AND task_id ~ '^([a-z][a-z-]{0,31}):([0-9]{1,19}):([vg][0-9]{1,19})$';

ALTER TABLE app.wecom_business_cards
    DROP CONSTRAINT wecom_business_cards_task_id_check,
    ADD CONSTRAINT wecom_business_cards_task_id_check CHECK (
        task_id ~ '^[a-z][a-z-]{0,31}:[0-9]{1,19}:[vg][0-9]{1,19}$'
        OR task_id ~ '^[a-z][a-z-]{0,31}_[0-9]{1,19}_[vg][0-9]{1,19}_[0-9a-f]{32}$'
        -- 2026-08-27 合流补充：企微线的规范 task_id（WecomTaskId.value()，无 hex 后缀）
        -- 已在生产运行（preship_19_v1 / preship-batch_26_v2 / export_…_g3 等），
        -- 版本断言由 id 内的 v/g 段承担，必须放行；缺这条曾把 V67 顶翻、全栈起不来。
        OR task_id ~ '^[a-z][a-z-]{0,31}_[0-9]{1,19}_[vg][0-9]{1,19}$'
    ),
    ADD CONSTRAINT uq_wecom_business_cards_entity_version
        UNIQUE (card_domain, entity_id, entity_version);

CREATE OR REPLACE FUNCTION app.reject_new_legacy_wecom_task_id()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_TABLE_NAME = 'wecom_order_draft_cards'
            AND NEW.task_id ~ '^order-draft:[1-9][0-9]*$' THEN
        RAISE EXCEPTION 'new order-draft task_id must use an opaque authorization reference'
            USING ERRCODE = '23514';
    END IF;
    IF TG_TABLE_NAME = 'wecom_business_cards'
            AND NEW.task_id ~ '^[a-z][a-z-]{0,31}:[0-9]{1,19}:[vg][0-9]{1,19}$' THEN
        RAISE EXCEPTION 'new business-card task_id must use an opaque authorization reference'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER reject_new_legacy_order_draft_task_id
BEFORE INSERT OR UPDATE OF task_id ON app.wecom_order_draft_cards
FOR EACH ROW EXECUTE FUNCTION app.reject_new_legacy_wecom_task_id();

CREATE TRIGGER reject_new_legacy_business_card_task_id
BEFORE INSERT OR UPDATE OF task_id ON app.wecom_business_cards
FOR EACH ROW EXECUTE FUNCTION app.reject_new_legacy_wecom_task_id();

