-- Follow-up identity and expected draft version arrive from the callback and are first facts.
-- approval_id is a processing result: it may be filled once after the Approval insert, then it is
-- immutable as well. This preserves the existing order-draft event guard in the same trigger.
CREATE OR REPLACE FUNCTION app.guard_wecom_card_event_first_facts()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.event_type IN ('template_card_event', 'business_followup_card_event') AND (
        NEW.event_type IS DISTINCT FROM OLD.event_type
        OR NEW.msgid IS DISTINCT FROM OLD.msgid
        OR NEW.aibot_id IS DISTINCT FROM OLD.aibot_id
        OR NEW.chat_id IS DISTINCT FROM OLD.chat_id
        OR NEW.chat_type IS DISTINCT FROM OLD.chat_type
        OR NEW.from_user_id IS DISTINCT FROM OLD.from_user_id
        OR NEW.create_time IS DISTINCT FROM OLD.create_time
        OR NEW.raw_payload IS DISTINCT FROM OLD.raw_payload
        OR NEW.event_key IS DISTINCT FROM OLD.event_key
        OR NEW.task_id IS DISTINCT FROM OLD.task_id
        OR NEW.order_draft_id IS DISTINCT FROM OLD.order_draft_id
        OR NEW.business_followup_id IS DISTINCT FROM OLD.business_followup_id
        OR NEW.business_followup_draft_version IS DISTINCT FROM OLD.business_followup_draft_version
        OR (OLD.business_followup_approval_id IS NOT NULL
            AND NEW.business_followup_approval_id IS DISTINCT FROM OLD.business_followup_approval_id)
    ) THEN
        RAISE EXCEPTION 'template-card first facts are immutable'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

