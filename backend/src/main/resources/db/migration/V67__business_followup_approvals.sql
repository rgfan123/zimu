CREATE TABLE app.business_followup_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    followup_id BIGINT NOT NULL,
    draft_version INTEGER NOT NULL CHECK (draft_version > 0),
    order_draft_id BIGINT,
    order_draft_revision BIGINT CHECK (order_draft_revision IS NULL OR order_draft_revision >= 0),
    designated_reviewer_operator_id BIGINT NOT NULL
        REFERENCES app.internal_operators(id) ON DELETE RESTRICT,
    decided_by_operator_id BIGINT NOT NULL
        REFERENCES app.internal_operators(id) ON DELETE RESTRICT,
    decision VARCHAR(24) NOT NULL CHECK (
        decision IN ('CONFIRM', 'REDO', 'NEEDS_INPUT', 'PAUSE')
    ),
    reason TEXT CHECK (
        (decision = 'CONFIRM' AND (reason IS NULL OR btrim(reason) <> ''))
        OR (decision <> 'CONFIRM' AND reason IS NOT NULL AND btrim(reason) <> '')
    ),
    source_kind VARCHAR(16) NOT NULL CHECK (source_kind IN ('WECOM_CARD', 'REST')),
    source_event_id BIGINT
        REFERENCES app.wecom_events(id) ON DELETE RESTRICT,
    request_id VARCHAR(128) NOT NULL CHECK (btrim(request_id) <> ''),
    idempotency_key VARCHAR(255) NOT NULL CHECK (btrim(idempotency_key) <> ''),
    request_fingerprint CHAR(64) NOT NULL
        CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    application_status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (
        application_status IN ('PENDING', 'APPLIED', 'FAILED', 'SUPERSEDED')
    ),
    application_failure_code VARCHAR(64) CHECK (
        application_failure_code IS NULL
        OR application_failure_code ~ '^[A-Z][A-Z0-9_]{2,63}$'
    ),
    applied_at TIMESTAMPTZ,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_business_followup_approval_draft
        FOREIGN KEY (followup_id, draft_version)
        REFERENCES app.business_followup_draft_versions(followup_id, version)
        ON DELETE RESTRICT,
    CONSTRAINT business_followup_approval_order_draft_pair_check CHECK (
        (order_draft_id IS NULL AND order_draft_revision IS NULL)
        OR (order_draft_id IS NOT NULL AND order_draft_revision IS NOT NULL)
    ),
    CONSTRAINT uq_business_followup_approval_draft UNIQUE (followup_id, draft_version),
    CONSTRAINT uq_business_followup_approval_request UNIQUE (request_id),
    CONSTRAINT uq_business_followup_approval_idempotency UNIQUE (followup_id, idempotency_key),
    CONSTRAINT business_followup_approval_source_check CHECK (
        (source_kind = 'WECOM_CARD' AND source_event_id IS NOT NULL)
        OR (source_kind = 'REST' AND source_event_id IS NULL)
    ),
    CONSTRAINT business_followup_approval_application_outcome_check CHECK (
        (application_status = 'PENDING'
            AND application_failure_code IS NULL AND applied_at IS NULL)
        OR (application_status = 'FAILED'
            AND application_failure_code IS NOT NULL AND applied_at IS NULL)
        OR (application_status IN ('APPLIED', 'SUPERSEDED')
            AND application_failure_code IS NULL AND applied_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_business_followup_approval_event
    ON app.business_followup_approvals(source_event_id)
    WHERE source_event_id IS NOT NULL;

CREATE INDEX idx_business_followup_approvals_operator
