-- 09（QUALITY 链路）：promptfoo 执行器结果回写表。
-- run_id 关联 agent_runs（run_mode=PREVIEW 行，不污染 LIVE 统计与 09 基线）；details 按
-- 用例索引记录每条得分（不落模型原始输出，避免敏感内容进库）；metric_kind 与
-- agent_eval_cases 对齐（T09 只写 QUALITY，INVARIANT 走 CI 基线 stub 跑分器）。
CREATE TABLE app.agent_eval_results (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         VARCHAR(36) NOT NULL,
    agent_slug     VARCHAR(64) NOT NULL
                   CHECK (agent_slug ~ '^[a-z][a-z0-9-]{0,63}$'),
    agent_version  INTEGER NOT NULL CHECK (agent_version > 0),
    metric_kind    VARCHAR(16) NOT NULL CHECK (metric_kind IN ('INVARIANT', 'QUALITY')),
    case_count     INTEGER NOT NULL CHECK (case_count >= 0),
    passed_count   INTEGER NOT NULL CHECK (passed_count >= 0),
    status         VARCHAR(16) NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    details        JSONB,
    started_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at    TIMESTAMPTZ,
    CONSTRAINT fk_agent_eval_results_definition
        FOREIGN KEY (agent_slug, agent_version)
        REFERENCES app.agent_definitions (agent_slug, version)
);

CREATE INDEX idx_agent_eval_results_run
    ON app.agent_eval_results(run_id);
CREATE INDEX idx_agent_eval_results_definition
    ON app.agent_eval_results(agent_slug, agent_version);
