CREATE TABLE app.fulfillments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fulfillment_no      VARCHAR(64) NOT NULL UNIQUE,
    order_line_id       BIGINT NOT NULL UNIQUE REFERENCES app.order_lines(id) ON DELETE RESTRICT,
    fulfillment_provider_id BIGINT NOT NULL REFERENCES app.fulfillment_providers(id) ON DELETE RESTRICT,
    requested_quantity NUMERIC(18,3) NOT NULL CHECK (requested_quantity > 0),
    cumulative_shipped_quantity NUMERIC(18,3) NOT NULL DEFAULT 0 CHECK (cumulative_shipped_quantity >= 0),
    cancelled_quantity NUMERIC(18,3) NOT NULL DEFAULT 0 CHECK (cancelled_quantity >= 0),
    shipping_progress   VARCHAR(32) NOT NULL DEFAULT 'NOT_SHIPPED'
                        CHECK (shipping_progress IN ('NOT_SHIPPED', 'PARTIALLY_SHIPPED', 'SHIPPED')),
    outcome             VARCHAR(32) NOT NULL DEFAULT 'IN_PROGRESS'
                        CHECK (outcome IN ('IN_PROGRESS', 'FULLY_FULFILLED', 'PARTIALLY_FULFILLED', 'CANCELLED')),
    exception_code      VARCHAR(64),
    exception_reason    TEXT,
    lock_version        BIGINT NOT NULL DEFAULT 0 CHECK (lock_version >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (btrim(fulfillment_no) <> ''),
    CHECK (cumulative_shipped_quantity + cancelled_quantity <= requested_quantity),
    CHECK (
        (shipping_progress = 'NOT_SHIPPED' AND cumulative_shipped_quantity = 0)
        OR (shipping_progress = 'PARTIALLY_SHIPPED' AND cumulative_shipped_quantity > 0 AND cumulative_shipped_quantity < requested_quantity)
        OR (shipping_progress = 'SHIPPED' AND cumulative_shipped_quantity = requested_quantity)
    ),
    CHECK (
        outcome = 'IN_PROGRESS'
        OR (outcome = 'FULLY_FULFILLED' AND cumulative_shipped_quantity = requested_quantity AND cancelled_quantity = 0)
        OR (outcome = 'PARTIALLY_FULFILLED' AND cumulative_shipped_quantity > 0 AND cancelled_quantity > 0
            AND cumulative_shipped_quantity + cancelled_quantity = requested_quantity)
        OR (outcome = 'CANCELLED' AND cumulative_shipped_quantity = 0 AND cancelled_quantity = requested_quantity)
    ),
    CHECK ((exception_code IS NULL) = (exception_reason IS NULL))
);

CREATE TABLE app.shipments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_no         VARCHAR(64) NOT NULL UNIQUE,
    order_id            BIGINT NOT NULL REFERENCES app.orders(id) ON DELETE RESTRICT,
    fulfillment_provider_id BIGINT NOT NULL REFERENCES app.fulfillment_providers(id) ON DELETE RESTRICT,
    outbound_order_no   VARCHAR(12) NOT NULL DEFAULT app.next_outbound_order_no(),
    shipment_sequence   INTEGER NOT NULL CHECK (shipment_sequence > 0),
    receiver_name_snapshot VARCHAR(200) NOT NULL,
    receiver_phone_snapshot VARCHAR(64) NOT NULL,
    receiver_address_snapshot TEXT NOT NULL,
    lock_version BIGINT NOT NULL DEFAULT 0 CHECK (lock_version >= 0),
    jd_receiver_province VARCHAR(64),
    jd_receiver_city VARCHAR(64),
    jd_receiver_county VARCHAR(64),
    jd_receiver_town VARCHAR(64),
    jd_receiver_detail_address VARCHAR(255),
    jd_receiver_confirmed_by VARCHAR(128),
    jd_receiver_confirmed_at TIMESTAMPTZ,
    shipment_status     VARCHAR(32) NOT NULL DEFAULT 'CREATED'
                        CHECK (shipment_status IN ('CREATED', 'SHIPPED', 'FAILED', 'DELIVERED')),
    failure_reason      TEXT,
    shipped_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (fulfillment_provider_id, outbound_order_no),
    UNIQUE (order_id, fulfillment_provider_id, shipment_sequence),
    CHECK (btrim(shipment_no) <> ''),
    CHECK (outbound_order_no ~ '^[0-9]{12}$'),
    CHECK (btrim(receiver_name_snapshot) <> ''),
    CHECK (btrim(receiver_phone_snapshot) <> ''),
    CHECK (btrim(receiver_address_snapshot) <> ''),
    CONSTRAINT shipments_jd_receiver_confirmation_consistency CHECK (
        (
            jd_receiver_confirmed_at IS NULL
            AND num_nonnulls(
