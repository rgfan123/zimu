CREATE TABLE app.import_batches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            VARCHAR(64) NOT NULL UNIQUE,
    batch_type          VARCHAR(32) NOT NULL
                        CHECK (batch_type IN ('SOURCE_ORDER', 'PROVIDER_TRACKING')),
    import_mode         VARCHAR(16) NOT NULL DEFAULT 'NEW'
                        CHECK (import_mode IN ('NEW', 'REVISION')),
    parent_import_batch_id BIGINT REFERENCES app.import_batches(id) ON DELETE RESTRICT,
    revision_no         INTEGER NOT NULL DEFAULT 1 CHECK (revision_no > 0),
    source_channel      VARCHAR(32)
                        CHECK (source_channel IS NULL OR source_channel IN ('CAISHIXIAN', 'JUFUBAO', 'FEIXIANG', 'ZHONGHUI', 'WECOM')),
    fulfillment_provider_id BIGINT REFERENCES app.fulfillment_providers(id) ON DELETE RESTRICT,
    source_fulfillment_export_id BIGINT,
    template_family     VARCHAR(128) NOT NULL,
    template_version    VARCHAR(64) NOT NULL,
    template_fingerprint VARCHAR(128) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    content_sha256      CHAR(64) NOT NULL,
    file_ref            TEXT NOT NULL,
    status              VARCHAR(32) NOT NULL DEFAULT 'RECEIVED'
                        CHECK (status IN ('RECEIVED', 'PROCESSING', 'COMPLETED', 'COMPLETED_WITH_REVIEW', 'FAILED')),
    error_detail        JSONB,
    uploaded_by         VARCHAR(128) NOT NULL,
    received_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at        TIMESTAMPTZ,
    confirmed_at        TIMESTAMPTZ,
    confirmed_by        VARCHAR(128),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (
        (batch_type = 'SOURCE_ORDER' AND source_channel IS NOT NULL
            AND fulfillment_provider_id IS NULL AND source_fulfillment_export_id IS NULL)
        OR
        (batch_type = 'PROVIDER_TRACKING' AND source_channel IS NULL
            AND fulfillment_provider_id IS NOT NULL AND source_fulfillment_export_id IS NOT NULL)
    ),
    CHECK (
        (import_mode = 'NEW' AND parent_import_batch_id IS NULL AND revision_no = 1)
        OR
        (import_mode = 'REVISION' AND parent_import_batch_id IS NOT NULL AND revision_no > 1)
    ),
    CHECK (parent_import_batch_id IS NULL OR parent_import_batch_id <> id),
    CHECK (btrim(batch_no) <> ''),
    CHECK (btrim(template_family) <> ''),
    CHECK (btrim(template_version) <> ''),
    CHECK (btrim(template_fingerprint) <> ''),
    CHECK (btrim(original_file_name) <> ''),
    CHECK (btrim(file_ref) <> ''),
    CHECK (btrim(uploaded_by) <> ''),
    CHECK (
        (confirmed_at IS NULL AND confirmed_by IS NULL)
        OR (batch_type='SOURCE_ORDER' AND confirmed_at IS NOT NULL AND btrim(confirmed_by) <> '')
    )
);

CREATE TABLE app.orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no            VARCHAR(64) NOT NULL UNIQUE,
    data_scope          VARCHAR(16) NOT NULL DEFAULT 'BUSINESS'
                        CHECK (data_scope IN ('BUSINESS', 'DEMO')),
    source_channel      VARCHAR(32) NOT NULL
                        CHECK (source_channel IN ('CAISHIXIAN', 'JUFUBAO', 'FEIXIANG', 'ZHONGHUI', 'WECOM')),
    source_ref          VARCHAR(128) NOT NULL,
    source_ref_kind     VARCHAR(16) NOT NULL
                        CHECK (source_ref_kind IN ('PROVIDED', 'SYNTHETIC')),
    source_version      VARCHAR(64),
    source_import_batch_id BIGINT REFERENCES app.import_batches(id) ON DELETE RESTRICT,
    customer_id         BIGINT REFERENCES app.customers(id) ON DELETE RESTRICT,
    correction_of_order_id BIGINT REFERENCES app.orders(id) ON DELETE RESTRICT,
    order_status        VARCHAR(32) NOT NULL DEFAULT 'RECEIVED'
                        CHECK (order_status IN (
                            'RECEIVED', 'VALIDATED', 'SKU_MAPPED', 'FULFILLING', 'SHIPPED', 'SYNCED', 'CLOSED',
                            'NEED_REVIEW', 'OUT_OF_STOCK', 'PROCUREMENT_PENDING', 'FULFILLMENT_EXCEPTION',
                            'SYNC_FAILED', 'CANCELLED'
                        )),
    settlement_method   VARCHAR(32) NOT NULL
                        CHECK (settlement_method IN ('MONTHLY', 'IMMEDIATE', 'CREDIT_TERM', 'PREPAID', 'COD', 'OTHER')),
    settlement_time     TIMESTAMPTZ NOT NULL,
    receiver_name       VARCHAR(200) NOT NULL,
    receiver_phone      VARCHAR(64) NOT NULL,
    receiver_address    TEXT NOT NULL,
    remark              TEXT,
    evidence_refs       JSONB NOT NULL DEFAULT '[]'::JSONB
                        CHECK (jsonb_typeof(evidence_refs) = 'array'),
    lock_version        BIGINT NOT NULL DEFAULT 0 CHECK (lock_version >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_channel, source_ref),
    CHECK (btrim(order_no) <> ''),
    CHECK (btrim(source_ref) <> ''),
    CHECK (btrim(receiver_name) <> ''),
    CHECK (btrim(receiver_phone) <> ''),
    CHECK (btrim(receiver_address) <> ''),
    CHECK (correction_of_order_id IS NULL OR correction_of_order_id <> id),
    CHECK (
        customer_id IS NOT NULL
        OR order_status IN ('RECEIVED', 'NEED_REVIEW', 'CANCELLED')
    ),
    CHECK (data_scope = 'DEMO' OR source_channel = 'WECOM' OR source_import_batch_id IS NOT NULL),
    CHECK (data_scope = 'DEMO' OR source_channel <> 'WECOM' OR source_import_batch_id IS NULL)
);

CREATE TABLE app.order_lines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES app.orders(id) ON DELETE RESTRICT,
    line_no             INTEGER NOT NULL CHECK (line_no > 0),
    line_type           VARCHAR(32) NOT NULL
                        CHECK (line_type IN ('SINGLE', 'CUSTOM_BUNDLE')),
    sku_id              BIGINT REFERENCES app.skus(id) ON DELETE RESTRICT,
    fulfillment_provider_id BIGINT REFERENCES app.fulfillment_providers(id) ON DELETE RESTRICT,
    product_name_snapshot VARCHAR(255) NOT NULL,
    sku_code_snapshot   VARCHAR(64),
    specification_snapshot VARCHAR(255) NOT NULL,
    unit_snapshot       VARCHAR(32) NOT NULL,
    source_quantity_snapshot NUMERIC(18,3) CHECK (source_quantity_snapshot > 0),
    mapping_multiplier_snapshot NUMERIC(18,3) CHECK (mapping_multiplier_snapshot > 0),
    requested_quantity NUMERIC(18,3) NOT NULL CHECK (requested_quantity > 0),
    processing_stage    VARCHAR(32) NOT NULL DEFAULT 'NEED_REVIEW'
                        CHECK (processing_stage IN (
                            'NEED_REVIEW', 'READY_TO_EXPORT', 'WAITING_PROVIDER', 'PROCUREMENT_IN_PROGRESS',
                            'TRACKING_RECEIVED', 'RETURN_FILE_READY', 'COMPLETED', 'EXCEPTION'
                        )),
    fulfillment_committed_at TIMESTAMPTZ,
    exception_code      VARCHAR(64),
    exception_reason    TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (order_id, line_no),
    CHECK (btrim(product_name_snapshot) <> ''),
    CHECK (btrim(specification_snapshot) <> ''),
    CHECK (btrim(unit_snapshot) <> ''),
    CHECK (line_type <> 'CUSTOM_BUNDLE' OR trunc(requested_quantity) = requested_quantity),
    CHECK (line_type <> 'CUSTOM_BUNDLE' OR sku_id IS NULL),
    CHECK (
        (source_quantity_snapshot IS NULL AND mapping_multiplier_snapshot IS NULL)
        OR (source_quantity_snapshot IS NOT NULL AND mapping_multiplier_snapshot IS NOT NULL)
    ),
    CHECK (
        line_type <> 'SINGLE'
        OR source_quantity_snapshot IS NULL
        OR requested_quantity = source_quantity_snapshot * mapping_multiplier_snapshot
    ),
    CHECK ((exception_code IS NULL) = (exception_reason IS NULL))
);

