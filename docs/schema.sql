CREATE VIEW app.v_order_progress_summary AS
WITH line_rollup AS (
    SELECT
        o.id AS order_id,
        count(ol.id)::INTEGER AS total_count,
        count(*) FILTER (WHERE ol.processing_stage = 'COMPLETED')::INTEGER AS completed_count,
        bool_or(ol.processing_stage = 'EXCEPTION') AS has_exception,
        bool_or(ol.processing_stage IN ('NEED_REVIEW', 'WAITING_PROVIDER', 'PROCUREMENT_IN_PROGRESS')) AS has_waiting,
        min(
            CASE ol.processing_stage
                WHEN 'NEED_REVIEW' THEN 10
                WHEN 'READY_TO_EXPORT' THEN 20
                WHEN 'PROCUREMENT_IN_PROGRESS' THEN 25
                WHEN 'WAITING_PROVIDER' THEN 30
                WHEN 'TRACKING_RECEIVED' THEN 40
                WHEN 'RETURN_FILE_READY' THEN 50
                WHEN 'COMPLETED' THEN 60
                WHEN 'EXCEPTION' THEN 100
            END
        ) FILTER (WHERE ol.processing_stage <> 'EXCEPTION') AS minimum_progress_rank,
        min(ol.exception_reason) FILTER (WHERE ol.processing_stage = 'EXCEPTION') AS line_exception_reason
    FROM app.orders o
    JOIN app.order_lines ol ON ol.order_id = o.id
    WHERE o.data_scope = 'BUSINESS'
    GROUP BY o.id
), alert_rollup AS (
    SELECT
        order_id,
        bool_or(severity = 'RED') AS has_red_alert,
        bool_or(severity = 'YELLOW') AS has_yellow_alert,
        min(message) AS first_alert_message
    FROM app.operational_alerts
    WHERE status IN ('OPEN', 'ACKNOWLEDGED')
    GROUP BY order_id
)
SELECT
    lr.order_id,
    CASE
        WHEN lr.has_exception THEN 'EXCEPTION'
        WHEN lr.completed_count = lr.total_count THEN 'COMPLETED'
        WHEN lr.minimum_progress_rank = 10 THEN 'NEED_REVIEW'
        WHEN lr.minimum_progress_rank = 20 THEN 'READY_TO_EXPORT'
        WHEN lr.minimum_progress_rank = 25 THEN 'PROCUREMENT_IN_PROGRESS'
        WHEN lr.minimum_progress_rank = 30 THEN 'WAITING_PROVIDER'
        WHEN lr.minimum_progress_rank = 40 THEN 'TRACKING_RECEIVED'
        WHEN lr.minimum_progress_rank = 50 THEN 'RETURN_FILE_READY'
        ELSE 'COMPLETED'
    END AS processing_stage,
    CASE
        WHEN lr.has_exception OR COALESCE(ar.has_red_alert, FALSE) THEN 'RED'
        WHEN lr.completed_count = lr.total_count THEN 'GREEN'
        WHEN lr.has_waiting OR COALESCE(ar.has_yellow_alert, FALSE) THEN 'YELLOW'
        ELSE 'BLUE'
    END AS processing_health,
    lr.completed_count,
    lr.total_count,
    COALESCE(lr.line_exception_reason, ar.first_alert_message) AS attention_reason
FROM line_rollup lr
LEFT JOIN alert_rollup ar ON ar.order_id = lr.order_id;

